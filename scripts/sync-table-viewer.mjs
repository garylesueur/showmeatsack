import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
const result = await build({
  entryPoints: ["src/table-viewer/main.tsx"],
  bundle: true,
  write: false,
  minify: true,
  format: "iife",
  target: "es2020",
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
});
const javascript = result.outputFiles.find(
  (file) => file.path.endsWith(".js") || file.path === "<stdout>",
).text;
const css =
  readFileSync("src/app/brand.generated.css", "utf8") +
  readFileSync("src/table-viewer/viewer.css", "utf8");
const output = `// Generated by scripts/sync-table-viewer.mjs. Do not edit.\nexport const TABLE_VIEWER_JS = ${JSON.stringify(javascript)};\nexport const TABLE_VIEWER_CSS = ${JSON.stringify(css)};\n`;
const path = "src/lib/table-viewer-bundle.generated.ts";
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output)
    throw new Error("Table viewer is stale. Run pnpm sync:table.");
} else writeFileSync(path, output);
